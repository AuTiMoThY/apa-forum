  `safenum` bigint(16) UNSIGNED NOT NULL DEFAULT 0,
  `colorsize` bigint(16) UNSIGNED NOT NULL DEFAULT 0,
  `letterSearch` varchar(255) DEFAULT NULL,
  `languageSearch` varchar(255) DEFAULT NULL,
  `shopNum` bigint(16) UNSIGNED NOT NULL DEFAULT 0,
  `chkdel` tinyint(1) UNSIGNED NOT NULL DEFAULT 0,
  `barcode` varchar(255) DEFAULT NULL,
  `combination_amount` varchar(255) DEFAULT NULL,
  `combination_price` varchar(255) DEFAULT NULL,
