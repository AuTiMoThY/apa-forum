SET NAMES utf8mb4;

-- ---------------------------------------------------------------------------
-- 台灣 分類表 pro_classlist
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `pro_classlist` (
  `classlistID` bigint(16) UNSIGNED NOT NULL AUTO_INCREMENT,
  `folderName` varchar(255) DEFAULT NULL,
  `classname` varchar(255) DEFAULT NULL,
  `classseries` varchar(255) DEFAULT NULL,
  `classmaster` bigint(16) UNSIGNED DEFAULT NULL,
  `chk_assembly` tinyint(1) UNSIGNED NOT NULL DEFAULT 0,
  `profile` longtext,
  `price` bigint(16) UNSIGNED NOT NULL DEFAULT 0,
  `item` bigint(16) UNSIGNED NOT NULL DEFAULT 0,
  `classordernum` bigint(16) UNSIGNED DEFAULT NULL,
  `chkdel` tinyint(1) UNSIGNED NOT NULL DEFAULT 0,
  `onTop` tinyint(1) UNSIGNED NOT NULL DEFAULT 1,
  `pic` varchar(255) DEFAULT NULL,
  PRIMARY KEY (`classlistID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

